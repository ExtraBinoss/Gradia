import { DEFAULT_CONFIG, parseConfig, type GradientConfig } from "./config";
export interface GradientPreset {
  id: string;
  name: string;
  config: GradientConfig;
  custom?: boolean;
}
function preset(
  id: string,
  name: string,
  colors: string[],
  patch: Partial<GradientConfig> = {},
): GradientPreset {
  return {
    id,
    name,
    config: parseConfig({
      ...DEFAULT_CONFIG,
      ...patch,
      colors: colors.map((color, i) => ({ id: `color-${i}`, color, enabled: true, influence: 1 })),
    }),
  };
}
